<?php

namespace App\Parity;

/**
 * Renders the parity matrix as PARITY.md.
 */
final class MatrixReport
{
    private const array TITLES = [
        'route' => 'Routes',
        'config' => 'Settings',
        'job' => 'Scheduled jobs',
        'table' => 'Database tables',
        'template' => 'Templates',
        'asset' => 'Static assets',
    ];

    private const array ICONS = ['todo' => '⬜', 'partial' => '🟨', 'done' => '✅', 'wontfix' => '➖'];

    public function __construct(
        private readonly Matrix $matrix,
        private readonly TestReferences $tests,
    ) {}

    public function render(): string
    {
        $out = [
            '# Parity with Vaultwarden',
            '',
            'Generated by `php artisan parity:report` from `parity/matrix.json` — do not edit by hand.',
            '',
            "Reference: dani-garcia/vaultwarden@`{$this->matrix->commit}`",
            '',
            'Status: ✅ done (needs a test) · 🟨 partial · ⬜ todo · ➖ won\'t fix',
            '',
            '| Area | Total | ✅ | 🟨 | ⬜ | ➖ | With tests |',
            '|---|--:|--:|--:|--:|--:|--:|',
        ];

        $byKind = [];
        foreach ($this->matrix->items as $id => $item) {
            $byKind[Matrix::string($item['kind'] ?? '')][$id] = $item;
        }

        foreach (Matrix::KINDS as $kind) {
            $items = $byKind[$kind] ?? [];
            $counts = array_count_values(array_map(static fn (array $item): string => Matrix::string($item['status'] ?? 'todo'), $items));
            $tested = count(array_filter(array_keys($items), fn (string $id): bool => $this->tests->for($id) !== []));

            $out[] = sprintf(
                '| %s | %d | %d | %d | %d | %d | %d |',
                self::TITLES[$kind], count($items), $counts['done'] ?? 0, $counts['partial'] ?? 0,
                $counts['todo'] ?? 0, $counts['wontfix'] ?? 0, $tested,
            );
        }

        foreach (Matrix::KINDS as $kind) {
            $out[] = '';
            $out[] = '## '.self::TITLES[$kind];
            $out[] = '';
            $out[] = '| | Item | Source | Tests | Notes |';
            $out[] = '|---|---|---|--:|---|';

            foreach ($byKind[$kind] ?? [] as $id => $item) {
                $label = match ($kind) {
                    'route' => Matrix::string($item['method'] ?? '').' `'.Matrix::string($item['path'] ?? '').'`',
                    'config' => '`'.Matrix::string($item['env'] ?? '').'`',
                    default => '`'.substr($id, strlen($kind) + 1).'`',
                };
                $notes = Matrix::string($item['notes'] ?? '');
                if (($item['upstream'] ?? null) === 'removed') {
                    $notes = trim('**Removed upstream.** '.$notes);
                }

                $out[] = sprintf(
                    '| %s | %s | %s | %d | %s |',
                    self::ICONS[Matrix::string($item['status'] ?? 'todo')] ?? '?',
                    $label,
                    Matrix::string($item['source'] ?? ''),
                    count($this->tests->for($id)),
                    str_replace('|', '\|', $notes),
                );
            }
        }

        return implode("\n", $out)."\n";
    }
}
